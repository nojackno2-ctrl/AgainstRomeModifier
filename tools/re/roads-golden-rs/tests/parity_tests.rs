use std::ffi::OsString;
use std::fs;
use std::path::PathBuf;

const EXPECTED_GOLDEN: &str = include_str!(
    "../../../../native/against-rome-navigation/tests/fixtures/connectivity_roads_golden.txt"
);

#[test]
fn test_cli_usage_on_missing_args() {
    let mut stdout = Vec::new();
    let mut stderr = Vec::new();
    let code = roads_golden::run_cli(&[], &mut stdout, &mut stderr);
    assert_eq!(code, 1);
    let err_str = String::from_utf8_lossy(&stderr);
    assert!(err_str.contains("Usage: roads-golden <output_file>"));
}

#[test]
fn test_cli_usage_on_too_many_args() {
    let mut stdout = Vec::new();
    let mut stderr = Vec::new();
    let args = vec![OsString::from("a"), OsString::from("b")];
    let code = roads_golden::run_cli(&args, &mut stdout, &mut stderr);
    assert_eq!(code, 1);
    let err_str = String::from_utf8_lossy(&stderr);
    assert!(err_str.contains("Usage:"));
}

#[test]
fn test_cli_generates_temp_file_matching_fixture_byte_for_byte() {
    let temp_dir = std::env::temp_dir();
    let target_path: PathBuf = temp_dir.join(format!(
        "connectivity_roads_golden_test_{}_{}.txt",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos()
    ));

    // Ensure target doesn't exist beforehand
    if target_path.exists() {
        let _ = fs::remove_file(&target_path);
    }

    let mut stdout = Vec::new();
    let mut stderr = Vec::new();
    let args = vec![target_path.as_os_str().to_os_string()];
    let code = roads_golden::run_cli(&args, &mut stdout, &mut stderr);
    assert_eq!(code, 0, "CLI should exit with code 0");

    let out_str = String::from_utf8_lossy(&stdout);
    assert!(out_str.contains("wrote 194 cases to"));

    // Read generated file bytes
    let generated_bytes = fs::read(&target_path).expect("read generated file in TEMP");
    assert_eq!(
        generated_bytes.len(),
        EXPECTED_GOLDEN.len(),
        "Byte length must match fixture: got {} vs expected {}",
        generated_bytes.len(),
        EXPECTED_GOLDEN.len()
    );

    assert_eq!(
        generated_bytes,
        EXPECTED_GOLDEN.as_bytes(),
        "Generated bytes in TEMP must match connectivity_roads_golden.txt byte-for-byte"
    );

    // Verify calling CLI again with the same target fails (no overwrite / create_new)
    let mut stdout2 = Vec::new();
    let mut stderr2 = Vec::new();
    let code2 = roads_golden::run_cli(&args, &mut stdout2, &mut stderr2);
    assert_eq!(code2, 1, "CLI must reject writing over existing file");
    let err_str2 = String::from_utf8_lossy(&stderr2);
    assert!(err_str2.contains("Error writing to"));

    // Clean up
    let _ = fs::remove_file(&target_path);
}
