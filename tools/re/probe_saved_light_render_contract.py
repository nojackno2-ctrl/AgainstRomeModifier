def validate_evidence(data, kind, name):
    """Separate static-result and REA-bundle schemas; missing binding never defaults."""
    def need(condition, detail):
        require(condition, f'{name}: evidence schema: {detail}')
    need(isinstance(data, dict), 'root must be object')
    if 'exe_sha256' in data:
        need(data['exe_sha256'] == EXE_SHA256, 'EXE hash mismatch')
    if kind in ('static', 'transform'):
        need('exe_sha256' in data, 'missing exe_sha256 for static result')
        need(isinstance(data.get('instructions'), list) and bool(data['instructions']),
             'missing/nonempty instructions')
        need(all(isinstance(line, str) and len(line.split(' ', 3)) >= 3
                 for line in data['instructions']), 'malformed instruction lines')
        need(isinstance(data.get('instruction_assertions'), int) and
             data['instruction_assertions'] > 0, 'missing positive instruction_assertions')
        if kind == 'static':
            need(data.get('light_column_widths') == list(WIDTHS), 'missing/mismatched column widths')
        else:
            need(isinstance(data.get('symbolic_xyz'), dict) and set(data['symbolic_xyz']) ==
                 {'dword ptr [esp + 0x20]', 'dword ptr [esp + 4]', 'dword ptr [esp]'},
                 'missing/malformed symbolic_xyz')
            need(data.get('callback_fields') == [67, 70, 71] and
                 data.get('owner_position_runtime_offset') == 12, 'transform metadata mismatch')
        return {'instruction_assertions': data['instruction_assertions'],
                'source_binding': 'exe_sha256'}
    need(kind == 'bundle', 'unsupported schema kind')
    need(isinstance(data.get('records'), list) and bool(data['records']), 'missing/nonempty records')
    records = []
    for index, record in enumerate(data['records']):
        need(isinstance(record, dict), f'record {index} must be object')
        subject = record.get('subject')
        need(isinstance(subject, dict) and isinstance(subject.get('digest'), dict),
             f'record {index} missing subject.digest')
        need(subject['digest'].get('sha256') == EXE_SHA256,
             f'record {index} missing/mismatched subject hash')
        for key in ('evidence_id', 'operation'):
            need(isinstance(record.get(key), str) and bool(record[key]), f'record {index} missing {key}')
        need(isinstance(record.get('parameters'), dict), f'record {index} missing parameters')
        records.append({'id': record['evidence_id'], 'operation': record['operation'],
                        'parameters': record['parameters']})
    return {'records': records, 'source_binding': 'every record subject.digest.sha256'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('exe', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    output = args.output.resolve()
    require(output.parent == (REPO / 're_workspace').resolve() and output.suffix == '.json',
            'output must be a new JSON directly in repository re_workspace')
    require(not output.exists(), 'refusing existing output')
    source = args.exe.read_bytes()
    result = inspect(source)
    reused = []
    for name, kind in (('native-light-pool-20261010.json', 'static'),
                       ('native-light-pool-20261010-evidence.json', 'bundle'),
                       ('direct-light-runtime-update-20261010-evidence.json', 'bundle'),
                       ('direct-light-transform-final-20261010.json', 'transform')):
        path = REPO / 're_workspace' / name
        raw = path.read_bytes()
        data = json.loads(raw)
        summary = validate_evidence(data, kind, name)
        if kind == 'transform':
            current = {a['address']: a for a in result['assertions']}
            matched = []
            for line in data['instructions']:
                address, encoded, mnemonic, *operands = line.split(' ', 3)
                if 0x49f8fa <= int(address, 16) <= 0x49f9d7:
                    expected = current.get(address)
                    require(expected is not None and
                            (encoded, mnemonic, operands[0] if operands else '') ==
                            (expected['bytes'], expected['mnemonic'], expected['operands']),
                            f'{name}: owner instruction disagreement at {address}')
                    matched.append(address)
            required_owner = {address for address in current
                              if 0x49f8fa <= int(address, 16) <= 0x49f9d7}
            require(set(matched) == required_owner,
                    f'{name}: incomplete owner transform coverage')
            summary['matched_owner_instructions'] = matched
            summary['symbolic_xyz'] = data['symbolic_xyz']
        reused.append({'path': str(path.relative_to(REPO)), 'sha256': hashlib.sha256(raw).hexdigest(),
                       'schema': kind, **summary})
        require(path.read_bytes() == raw, f'{name}: evidence changed during read')
    require(args.exe.read_bytes() == source, 'EXE changed during proof')
    result.update({'reused_evidence': reused, 'source_unchanged': True,
                   'probe_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                   'tool_versions': {'capstone': capstone.__version__, 'pefile': pefile.__version__}})
    with output.open('x', encoding='utf-8') as stream:
        json.dump(result, stream, indent=2, ensure_ascii=False)
        stream.write('\n')
    print(json.dumps({'output': str(output), 'instruction_assertions': result['instruction_assertions'],
                      'exe_sha256': EXE_SHA256, 'source_unchanged': True}))


if __name__ == '__main__':
    main()
