    [Fact]
    public void EditorModule_AutoGeneratedZones_LifecycleAndFiltering()
    {
        var module = new SoundscapeEditorModule();
        var manualZone = new SoundscapeZone { Name = "Manual Forge" };
        module.AddZone(manualZone);
        module.AcceptChanges();

        Assert.Equal(0, module.ClearAutoGeneratedZones());
        Assert.False(module.IsDirty);

        var autoZone1 = new SoundscapeZone { Name = "Auto River" };
        var autoZone2 = new SoundscapeZone { Name = "Auto Forest" };
        module.AddAutoGeneratedZones([autoZone1, autoZone2]);

        Assert.Equal(3, module.Zones.Count);
        Assert.True(module.Zones[1].Flags.HasFlag(SoundscapeZoneAttributes.IsAutoGenerated));
        Assert.True(module.Zones[2].Flags.HasFlag(SoundscapeZoneAttributes.IsAutoGenerated));

        int cleared = module.ClearAutoGeneratedZones();
        Assert.Equal(2, cleared);
        Assert.Single(module.Zones);
        Assert.Equal("Manual Forge", module.Zones[0].Name);
    }

    [Fact]
    public void EditorModule_UndoRedo_EmptyStack_ReturnsFalse()
