    [Fact]
    public void EditorModule_GlobalAmbienceProperties_PushUndoOnlyOnValueChange()
    {
        var module = new SoundscapeEditorModule();
        string initialAmbience = module.GlobalAmbienceId;
        float initialVol = module.GlobalAmbienceVolume;

        // 設定相同值不應觸發 Undo
        module.GlobalAmbienceId = initialAmbience;
        Assert.False(module.CanUndo);

        module.GlobalAmbienceVolume = initialVol;
        Assert.False(module.CanUndo);

        // 設定新值觸發 Undo
        module.GlobalAmbienceId = "Amb_New_Track";
        Assert.True(module.CanUndo);
        Assert.Equal("Amb_New_Track", module.GlobalAmbienceId);

        module.Undo();
        Assert.Equal(initialAmbience, module.GlobalAmbienceId);

        module.GlobalAmbienceVolume = 0.95f;
        Assert.True(module.CanUndo);
        Assert.Equal(0.95f, module.GlobalAmbienceVolume, 3);

        module.Undo();
        Assert.Equal(initialVol, module.GlobalAmbienceVolume, 3);
    }

