    [Fact]
    public void EditorModule_GuardsAgainstNullArguments()
    {
        var module = new SoundscapeEditorModule();
        Assert.Throws<ArgumentNullException>(() => module.Load(null!));
        Assert.Throws<ArgumentNullException>(() => module.AddZone(null!));
        Assert.Throws<ArgumentNullException>(() => module.UpdateZone(null!));
        Assert.Throws<ArgumentNullException>(() => module.AddAutoGeneratedZones(null!));
    }

    [Fact]
    public void EditorModule_RemoveAndUpdate_NonExistentZone_ReturnsFalseWithoutDirtying()
    {
        var module = new SoundscapeEditorModule();
        Assert.False(module.IsDirty);

        bool removed = module.RemoveZone(Guid.NewGuid());
        Assert.False(removed);
        Assert.False(module.IsDirty);
        Assert.False(module.CanUndo);

        var ghostZone = new SoundscapeZone { Id = Guid.NewGuid(), Name = "Ghost" };
        bool updated = module.UpdateZone(ghostZone);
        Assert.False(updated);
        Assert.False(module.IsDirty);
        Assert.False(module.CanUndo);
    }

    [Fact]
    public void EditorModule_AddAutoGeneratedZones_EmptyIsNoOp()
    {
