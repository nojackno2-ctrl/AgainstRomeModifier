    [Fact]
    public void Catalog_DistancePointToSegment_DegenerateSegmentLengthZero()
    {
        // 長度為 0 的線段退化為單一點 (10, 10)
        float dist = SoundscapeZoneCatalog.DistancePointToSegment(13f, 14f, 10f, 10f, 10f, 10f);
        Assert.Equal(5f, dist, 2); // sqrt((13-10)^2 + (14-10)^2) = 5
    }

    [Fact]
    public void Catalog_CalculateAttenuation_EdgeCases()
    {
        // 內半徑大於等於外半徑：若距離大於外半徑 (如 250f > 100f) 則衰減為 0
        Assert.Equal(0f, SoundscapeZoneCatalog.CalculateAttenuation(250f, 200f, 100f, AttenuationCurveKind.Linear));

        // 距離等於內半徑：永遠為 1.0f (優先判定 distance <= innerRadius)
        Assert.Equal(1f, SoundscapeZoneCatalog.CalculateAttenuation(100f, 100f, 100f, AttenuationCurveKind.Linear));

        // 距離小於等於內半徑：永遠為 1.0f
        Assert.Equal(1f, SoundscapeZoneCatalog.CalculateAttenuation(0f, 50f, 200f, AttenuationCurveKind.Logarithmic));
        Assert.Equal(1f, SoundscapeZoneCatalog.CalculateAttenuation(50f, 50f, 200f, AttenuationCurveKind.Exponential));

        // 距離大於等於外半徑：永遠為 0.0f
        Assert.Equal(0f, SoundscapeZoneCatalog.CalculateAttenuation(300f, 50f, 200f, AttenuationCurveKind.SmoothStep));
    }

    [Fact]
    public void Catalog_Resolve_UnknownSoundId_ReturnsFallbackDefinition()
    {
        var catalog = new SoundscapeZoneCatalog();
        var def = catalog.Resolve("Unknown_Custom_Sound");
        Assert.NotNull(def);
        Assert.Equal("Unknown_Custom_Sound", def.SoundId);
        Assert.Equal(AudioCategory.AmbientZone, def.Category);
        Assert.Equal(SoundTriggerMode.ContinuousLoop, def.TriggerMode);
    }
