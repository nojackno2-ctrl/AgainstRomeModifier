//! Shared implementation for the Cargo example and its integration tests.
use serde::Deserialize;
use std::{ffi::OsString, fmt::Write as _, fs, path::PathBuf};

pub const HEADER: &str = "// Generated by examples/generate-app-tables.rs from tools/app_tables.json; do not hand-edit.\n";

#[derive(Debug, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Tables {
    #[serde(rename = "ZH")]
    zh: Vec<(String, String)>,
    #[serde(rename = "EN")]
    en: Vec<(String, String)>,
    #[serde(rename = "EN_UNIT_NAMES")]
    en_unit_names: Vec<(String, String)>,
    #[serde(rename = "ZH_UNIT_NAMES")]
    zh_unit_names: Vec<(String, String)>,
}

// Keep historical spellings and readable Unicode while escaping Rust controls.
pub fn rust_literal(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\r' => out.push_str("\\r"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            c if c.is_control() => write!(out, "\\u{{{:x}}}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub fn render(json: &str) -> Result<String, serde_json::Error> {
    let tables: Tables = serde_json::from_str(json)?;
    let mut out = HEADER.to_owned();
    for (name, entries) in [
        ("ZH", tables.zh),
        ("EN", tables.en),
        ("EN_UNIT_NAMES", tables.en_unit_names),
        ("ZH_UNIT_NAMES", tables.zh_unit_names),
    ] {
        writeln!(out, "pub const {name}: &[(&str, &str)] = &[").unwrap();
        for (key, value) in entries {
            writeln!(
                out,
                "    ({}, {}),",
                rust_literal(&key),
                rust_literal(&value)
            )
            .unwrap();
        }
        out.push_str("];\n");
    }
    Ok(out)
}

/// `--check` only reads, including when the output is missing or stale.
pub fn run(args: impl IntoIterator<Item = OsString>) -> Result<(), String> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut output = root.join("src/app_tables.rs");
    let mut check = false;
    let mut output_seen = false;
    let mut args = args.into_iter();
    while let Some(arg) = args.next() {
        if arg == "--check" && !check {
            check = true;
        } else if arg == "--output" && !output_seen {
            output = args.next().ok_or("--output requires a path")?.into();
            output_seen = true;
        } else {
            return Err("usage: generate-app-tables [--check] [--output PATH]".into());
        }
    }
    let json = fs::read_to_string(root.join("tools/app_tables.json"))
        .map_err(|e| format!("read canonical tables: {e}"))?;
    let expected = render(&json).map_err(|e| format!("parse canonical tables: {e}"))?;
    if check {
        let actual = fs::read(&output).map_err(|e| format!("check {}: {e}", output.display()))?;
        if actual != expected.as_bytes() {
            return Err(format!(
                "stale generated tables: {}; run the generator without --check",
                output.display()
            ));
        }
    } else {
        fs::write(&output, expected.as_bytes())
            .map_err(|e| format!("write {}: {e}", output.display()))?;
    }
    Ok(())
}
