# Regenerate immutable data from C# without requiring C# at Rust runtime.
$ErrorActionPreference = 'Stop'
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../..'))
$source = Get-Content (Join-Path $repo 'src.Core/Core/Localization.cs') -Raw -Encoding UTF8
$troops = Get-Content (Join-Path $repo 'src.Core/Core/TroopConfig.cs') -Raw -Encoding UTF8
function RustLiteral([string]$value) {
    '"' + $value.Replace('\','\\').Replace('"','\"').Replace("`r",'\r').Replace("`n",'\n').Replace("`t",'\t').Replace([string][char]0,'\0') + '"'
}
$pairPattern = '\{\s*"((?:\\.|[^"\\])*)"\s*,\s*"((?:\\.|[^"\\])*)"\s*\}'
$output = [Text.StringBuilder]::new("// Generated by tools/generate-app-tables.ps1 from C#; do not hand-edit.`n")
foreach ($item in @(@('ZH','Zh',$source), @('EN','En',$source), @('EN_UNIT_NAMES','EnUnitNames',$source), @('ZH_UNIT_NAMES','UnitNames',$troops))) {
    $section = [regex]::Match($item[2], ('(?s)Dictionary<string, string>\s+' + $item[1] + '\s*=.*?\{(.*?)\n\s*\};'))
    if (!$section.Success) { throw "Missing table $($item[1])" }
    [void]$output.Append("pub const $($item[0]): &[(&str, &str)] = &[`n")
    $pairs = [regex]::Matches($section.Groups[1].Value, $pairPattern)
    foreach ($pair in $pairs) {
        $key = ('"' + $pair.Groups[1].Value + '"') | ConvertFrom-Json
        $value = ('"' + $pair.Groups[2].Value + '"') | ConvertFrom-Json
        [void]$output.Append('    (' + (RustLiteral $key) + ', ' + (RustLiteral $value) + "),`n")
    }
    [void]$output.Append("];`n")
    Write-Output "$($item[0]): $($pairs.Count)"
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '../src/app_tables.rs'), $output.ToString(), [Text.UTF8Encoding]::new($false))
