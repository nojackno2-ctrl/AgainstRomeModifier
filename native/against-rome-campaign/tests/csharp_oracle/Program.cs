﻿// Generates Rust tables + fixtures from the REAL .NET 8 runtime and the real
// CampaignMissionCompiler.SanitizeName (private, via reflection).
// Usage: dotnet run -c Release -- <rust_table_out.rs> <fixture_dir>
using System.Reflection;
using System.Text;
using AgainstRomeMapEditor.Modules.AI;

var tablePath = args[0];
var fixDir = args[1];
Directory.CreateDirectory(fixDir);

var sanitize = typeof(CampaignMissionCompiler).GetMethod("SanitizeName", BindingFlags.NonPublic | BindingFlags.Static)
    ?? throw new InvalidOperationException("SanitizeName not found");
string San(string s) => (string)sanitize.Invoke(null, new object[] { s })!;

// 1. char.IsLetterOrDigit over every UTF-16 unit -> ranges
var ranges = new List<(int s, int e)>();
int start = -1;
for (int u = 0; u <= 0x10000; u++)
{
    bool on = u < 0x10000 && char.IsLetterOrDigit((char)u);
    if (on && start < 0) start = u;
    if (!on && start >= 0) { ranges.Add((start, u - 1)); start = -1; }
}

// 2. OrdinalIgnoreCase folding over every Unicode scalar value
var fold = new List<(int c, int k)>();
var canon = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
int unfolded = 0, conflicts = 0;
for (int cp = 0; cp <= 0x10FFFF; cp++)
{
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    var r = new Rune(cp);
    var k = Rune.ToUpperInvariant(r);
    string sc = r.ToString();
    if (k.Value != cp)
    {
        if (string.Equals(sc, k.ToString(), StringComparison.OrdinalIgnoreCase)) fold.Add((cp, k.Value));
        else { unfolded++; k = r; }
    }
    if (canon.TryGetValue(k.ToString(), out var prev) && prev != k.Value) { conflicts++; Console.Error.WriteLine($"fold conflict {prev:X} vs {k.Value:X}"); }
    else canon[k.ToString()] = k.Value;
}
Console.WriteLine($"letter/digit ranges={ranges.Count} fold={fold.Count} unfolded={unfolded} conflicts={conflicts}");
if (conflicts > 0) return 1;

var rs = new StringBuilder();
rs.AppendLine("// @generated by tests/csharp_oracle (net8.0 runtime). Do not edit; regenerate with the oracle.");
rs.AppendLine("// BMP code units for which .NET `char.IsLetterOrDigit` is true (inclusive ranges).");
rs.AppendLine("pub(crate) const LETTER_OR_DIGIT_BMP: &[(u16, u16)] = &[");
foreach (var (s, e) in ranges) rs.AppendLine($"    (0x{s:X4}, 0x{e:X4}),");
rs.AppendLine("];");
rs.AppendLine();
rs.AppendLine("// (code point, OrdinalIgnoreCase canonical code point) for scalars that fold to something else.");
rs.AppendLine("pub(crate) const ORDINAL_IGNORE_CASE_FOLD: &[(u32, u32)] = &[");
foreach (var (c, k) in fold) rs.AppendLine($"    (0x{c:X}, 0x{k:X}),");
rs.AppendLine("];");
File.WriteAllText(tablePath, rs.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));

static string Hex(string s) => string.Join(' ', s.Select(c => ((int)c).ToString("X4")));
static string Dot(string s) => s.Length == 0 ? "-" : Hex(s).Replace(' ', '.');

// 3. sanitize cases: input and expected output as UTF-16 hex units
var inputs = new List<string>
{
    "", " ", "  \t", "!!!", "_a_", "__", "abc", "Siege of Aquileia!", "保護城鎮中心", "Wave 01", "a-b_c",
    "Ⅷ", "²", "½", "٣", "①", "ǅ", "ʰ", "ªº", "́á", "á", "́", "ａｂｃ１２３", "ß", "İ", "ı", "K",
    "😀", "a😀b", "𠀀", "a𠀀b", "𝐀𝐁", "𝟏", "𐐨", "x𐐨y", "\U0001F600abc", "abc\U00020000",
    "\u200Babc", "a\u00A0b", "\u3000abc", "\u2028", "\u2029x", "\u0085", "漢字 かな カナ", "Ünïcödé", "Αθήνα", "Привет мир",
    new string('字', 40), new string('a', 40), new string('a', 29) + "😀", new string('a', 30) + "b",
    new string('a', 28) + "😀x", new string('a', 29) + "字", new string('a', 31) + "_", "_" + new string('a', 40),
    string.Concat(Enumerable.Repeat("😀", 20)), new string('字', 15) + "😀" + new string('字', 15), "a" + new string('!', 40) + "b",
    new string('a', 29) + "!" + "b", new string('a', 28) + "!!" + "b", string.Concat(Enumerable.Repeat("𠀀", 16)),
};
var rnd = new Random(20261018);
int[] pools = { 0x20, 0x21, 0x5F, 0x30, 0x41, 0x61, 0xDF, 0x130, 0x3A3, 0x416, 0x4E00, 0x3042, 0x30AB, 0xFF21, 0x2160, 0x00B2, 0x0301, 0x0660, 0x200B, 0xA0, 0x1F600, 0x20000, 0x1D400, 0x10428, 0xAC00 };
for (int i = 0; i < 3000; i++)
{
    var sb = new StringBuilder();
    int len = rnd.Next(1, 45);
    for (int j = 0; j < len; j++)
    {
        int cp = rnd.Next(4) == 0 ? rnd.Next(0x20, 0xD7FF) : pools[rnd.Next(pools.Length)];
        sb.Append(char.ConvertFromUtf32(cp));
    }
    inputs.Add(sb.ToString());
}
var cases = new StringBuilder();
foreach (var s in inputs) cases.Append(Dot(s)).Append('\t').Append(Dot(San(s))).Append('\n');
File.WriteAllText(Path.Combine(fixDir, "dotnet_sanitize_cases.tsv"), cases.ToString(), new UTF8Encoding(false));

// 4. event-name collision cases, mirroring MapEditorForm.UniqueEventNames
var coll = new StringBuilder();
string[][] existing = { new[] { "Wave_Ünï" }, new[] { "ΑΘΉΝΑ" }, new[] { "straße" }, new[] { "wave_01", "WAVE_01_2" }, new[] { "Привет" }, new[] { "ǆ" }, new[] { "ß", "ẞ" }, new[] { "𐐨" }, new[] { "ı" }, new[] { "K" }, Array.Empty<string>() };
string[][] incoming = { new[] { "Wave_ÜNÏ", "wave_ünï" }, new[] { "αθήνα", "ΑΘΉΝΑ" }, new[] { "STRASSE", "STRAßE", "strAße" }, new[] { "Wave_01", "WAVE_01" }, new[] { "ПРИВЕТ", "привет" }, new[] { "ǅ", "Ǆ" }, new[] { "SS", "ẞ", "ß" }, new[] { "𐐀", "𐐨" }, new[] { "I", "ı", "İ" }, new[] { "k", "K", "K" }, new[] { "A", "a", "A_2", "a_2" } };
for (int i = 0; i < existing.Length; i++)
{
    var used = new HashSet<string>(existing[i], StringComparer.OrdinalIgnoreCase);
    var outp = new List<string>();
    foreach (var n0 in incoming[i])
    {
        string name = n0;
        for (int n = 2; !used.Add(name); n++) name = $"{n0}_{n}";
        outp.Add(name);
    }
    coll.Append(string.Join(',', existing[i].Select(Dot))).Append('\t')
        .Append(string.Join(',', incoming[i].Select(Dot))).Append('\t')
        .Append(string.Join(',', outp.Select(Dot))).Append('\n');
}
File.WriteAllText(Path.Combine(fixDir, "dotnet_event_name_collision_cases.tsv"), coll.ToString().Replace("\t\t", "\t-\t"), new UTF8Encoding(false));

// 5. alias-membership cases: knownAliases.Contains(alias, OrdinalIgnoreCase)
var al = new StringBuilder();
string[] known = { "Legionary", "Ünï", "ΑΘΉΝΑ", "straße", "Привет", "ǆ", "𐐨", "ı", "K" };
string[] probes = { "legionary", "LEGIONARY", "ÜNÏ", "ünï", "αθήνα", "ΑΘΉΝΑ", "STRASSE", "STRAßE", "ПРИВЕТ", "ǅ", "Ǆ", "𐐀", "I", "İ", "K", "k", "x", "" };
al.Append("KNOWN\t").Append(string.Join(',', known.Select(Dot))).Append('\n');
foreach (var p in probes)
    al.Append(Dot(p)).Append('\t').Append(known.Contains(p, StringComparer.OrdinalIgnoreCase) ? '1' : '0').Append('\n');
File.WriteAllText(Path.Combine(fixDir, "dotnet_alias_cases.tsv"), al.ToString(), new UTF8Encoding(false));
Console.WriteLine($"cases={inputs.Count}");
return 0;
