// Differential fixture generator: runs the real C# FormationWidthValidator / NavMeshPassabilityGrid
// over deterministic cases and records inputs + outputs for the Rust tests.
// Usage: dotnet run --project <this csproj> -- <output file>
using System.Globalization;
using System.Reflection;
using System.Text;
using AgainstRomeMapEditor.Modules.Pathfinding;

uint state = 0x9E3779B9;
uint Next() { state ^= state << 13; state ^= state >> 17; state ^= state << 5; return state; }
int Rnd(int n) => (int)(Next() % (uint)n);
string F(float v) => BitConverter.SingleToUInt32Bits(v).ToString(CultureInfo.InvariantCulture);
string Hex(byte[]? b) => b is null || b.Length == 0 ? "-" : Convert.ToHexString(b);
string Coord(NavMeshCoordinate c) => $"{c.TileX} {c.TileZ} {F(c.WorldX)} {F(c.WorldZ)}";
string Choke(FormationChokePoint c) =>
    $"{Coord(c.Location)} {c.MeasuredClearanceTiles} {F(c.MeasuredWidthUnits)} {c.RequiredClearanceTiles} {F(c.RequiredWidthUnits)} {c.MaxSafeUnitCount} {c.BlockedTroopCount} {c.ChokeType}";

var findPath = typeof(FormationWidthValidator).GetMethod("FindPath", BindingFlags.NonPublic | BindingFlags.Static)!;
var sb = new StringBuilder();
sb.AppendLine("# generated by tools/csharp-golden from src.MapEditor.Modules/Pathfinding; do not edit");

for (int n = -5; n <= 25; n++)
{
    var (t, w) = FormationWidthValidator.GetRequiredClearance(n);
    sb.AppendLine($"REQ {n} {t} {F(w)}");
}
for (int c = -2; c <= 9; c++)
    sb.AppendLine($"SAFE {c} {FormationWidthValidator.GetMaxSafeUnitCount(c)}");

int[] troopChoices = [-3, 0, 1, 2, 5, 6, 10, 11, 15, 16, 20, 30];
float[] worlds = [16384f, 16384f, 16384f, 1000f, 7777.5f];

void EmitCase(int id, int size, byte[]? collision, int hs, byte[]? heights, float step, float water, float world,
    List<(int sx, int sz, int tx, int tz, int n)> trips, int minTroop)
{
    var grid = new NavMeshPassabilityGrid(size, collision, hs, heights, step, water, world);
    sb.AppendLine($"CASE {id}");
    sb.AppendLine($"GRID {size} {F(world)} {Hex(collision)} {hs} {F(step)} {F(water)} {Hex(heights)}");
    var pass = new StringBuilder(); var sub = new StringBuilder(); var blk = new StringBuilder(); var cb = new StringBuilder();
    for (int z = -1; z <= size; z++)
        for (int x = -1; x <= size; x++)
        {
            pass.Append(grid.IsPassable(x, z) ? '1' : '0');
            sub.Append(grid.IsSubmerged(x, z) ? '1' : '0');
            blk.Append(grid.IsBlockedByCollision(x, z) ? '1' : '0');
            cb.Append(grid.GetCollisionByte(x, z).ToString("X2"));
        }
    sb.AppendLine($"PASS {pass}");
    sb.AppendLine($"SUB {sub}");
    sb.AppendLine($"BLK {blk}");
    sb.AppendLine($"CBYTE {cb}");
    foreach (int dim in (size <= 12 ? new[] { 0, 1, 3, Math.Max(1, size / 2), size, size + 3, size * 2 + 1 } : new[] { 0, 1, 3, Math.Max(1, size / 2), size, size + 3 }))
    {
        var tb = new StringBuilder(); var ts = new StringBuilder();
        for (int z = 0; z < dim; z++)
            for (int x = 0; x < dim; x++)
            {
                tb.Append(grid.IsTileBlockedByCollision(x, z, dim) ? '1' : '0');
                ts.Append(grid.IsTileSubmerged(x, z, dim) ? '1' : '0');
            }
        sb.AppendLine($"TILE {dim} {(tb.Length == 0 ? "-" : tb)} {(ts.Length == 0 ? "-" : ts)}");
    }
    float[] probes = [-50f, 0f, 1f, world / size * 0.5f, world / 3f, world - 0.01f, world, world * 2f];
    for (int i = 0; i < probes.Length; i++)
    {
        float px = probes[i], pz = probes[(i + 3) % probes.Length];
        var (tx, tz) = grid.WorldToTile(px, pz);
        sb.AppendLine($"W2T {F(px)} {F(pz)} {tx} {tz} {F(grid.TileScale)}");
    }
    var field = FormationWidthValidator.ComputeClearanceField(grid);
    sb.AppendLine("CLEAR " + string.Join(' ', field));
    var tripArgs = new List<(NavMeshCoordinate, NavMeshCoordinate, int)>();
    for (int i = 0; i < trips.Count; i++)
    {
        var (sx, sz, tx, tz, n) = trips[i];
        sb.AppendLine($"TRIP {i} {sx} {sz} {tx} {tz} {n}");
        var path = (List<(int X, int Z)>?)findPath.Invoke(null, [grid, sx, sz, tx, tz]);
        sb.AppendLine(path is null ? $"PATH {i} none" : $"PATH {i} {path.Count} " + string.Join(';', path.Select(p => $"{p.X},{p.Z}")));
        // Corridor input only consumes TileX/TileZ of the coordinates.
        tripArgs.Add((new NavMeshCoordinate(sx, sz, 0, 0), new NavMeshCoordinate(tx, tz, 0, 0), n));
    }
    foreach (var c in FormationWidthValidator.EvaluateCorridors(grid, tripArgs)) sb.AppendLine("CORR " + Choke(c));
    sb.AppendLine($"TOPOARG {minTroop}");
    foreach (var c in FormationWidthValidator.DetectTopologicalChokePoints(grid, minTroop)) sb.AppendLine("TOPO " + Choke(c));
    sb.AppendLine("END");
}

List<(int, int, int, int, int)> RandTrips(int size)
{
    var l = new List<(int, int, int, int, int)>();
    int count = Rnd(7);
    for (int i = 0; i < count; i++)
        l.Add((Rnd(size + 2) - 1, Rnd(size + 2) - 1, Rnd(size + 2) - 1, Rnd(size + 2) - 1, troopChoices[Rnd(troopChoices.Length)]));
    return l;
}

int id = 0;
int[] densities = [0, 5, 15, 30, 50];
for (int i = 0; i < 220; i++)
{
    int size = i < 40 ? 1 + i : (i % 25 == 0 ? 64 : 1 + Rnd(40));
    int density = densities[Rnd(densities.Length)];
    var coll = new byte[size * size];
    for (int k = 0; k < coll.Length; k++) coll[k] = Rnd(100) < density ? (byte)(Rnd(255) + 1) : (byte)0;
    byte[]? collision = Rnd(10) == 0 ? new byte[size * size + 1] : (Rnd(12) == 0 ? null : coll);
    int hs = 0; byte[]? heights = null; float step = 4f, water = 0f;
    int hmode = Rnd(4);
    if (hmode != 0)
    {
        hs = hmode == 1 ? size + 1 : hmode == 2 ? Math.Max(1, size / 2 + 1) : size * 2 + 1;
        if (Rnd(15) == 0) hs = 1;
        int len = hs * hs + (Rnd(15) == 0 ? 1 : 0);
        heights = new byte[len];
        for (int k = 0; k < len; k++) heights[k] = (byte)Rnd(256);
        step = Rnd(12) == 0 ? (Rnd(2) == 0 ? 0f : float.NaN) : (Rnd(2) == 0 ? 4f : 1.5f);
        water = Rnd(20) == 0 ? float.NaN : Rnd(400);
    }
    EmitCase(id++, size, collision, hs, heights, step, water, worlds[Rnd(worlds.Length)],
        RandTrips(size), troopChoices[Rnd(troopChoices.Length)]);
}
// Structured corridor / canyon cases: a vertical lane of width w through a wall band.
foreach (int size in new[] { 24, 32 })
foreach (int w in new[] { 1, 2, 3, 4, 5, 6, 7 })
{
    var coll = new byte[size * size];
    int x0 = size / 2 - w / 2;
    for (int z = size / 4; z < size * 3 / 4; z++)
        for (int x = 0; x < size; x++)
            if (x < x0 || x >= x0 + w) coll[z * size + x] = 255;
    var trips = new List<(int, int, int, int, int)>();
    foreach (int n in new[] { 2, 6, 11, 16, 20 }) trips.Add((x0, 1, x0, size - 2, n));
    EmitCase(id++, size, coll, 0, null, 4f, 0f, 16384f, trips, 10);
    EmitCase(id++, size, coll, 0, null, 4f, 0f, 16384f, new(), 20);
}
