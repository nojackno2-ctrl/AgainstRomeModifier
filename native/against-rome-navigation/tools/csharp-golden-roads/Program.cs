// Differential fixture generator for NavMeshConnectivityAnalyzer / RoadGapDetector / RoadPathHealer.
// Usage: dotnet run --project <this csproj> -- <output file>
using System.Globalization;
using System.Text;
using AgainstRomeMapEditor.Modules.Pathfinding;

uint state = 0xC0FFEE11;
uint Next() { state ^= state << 13; state ^= state >> 17; state ^= state << 5; return state; }
int Rnd(int n) => (int)(Next() % (uint)n);
string F(float v) => BitConverter.SingleToUInt32Bits(v).ToString(CultureInfo.InvariantCulture);
string Hex(byte[]? b) => b is null || b.Length == 0 ? "-" : Convert.ToHexString(b);
string Coord(NavMeshCoordinate c) => $"{c.TileX} {c.TileZ} {F(c.WorldX)} {F(c.WorldZ)}";
string Pts(IEnumerable<(int, int)> p) { var s = string.Join(';', p.Select(q => $"{q.Item1},{q.Item2}")); return s.Length == 0 ? "-" : s; }
string Tex(string t) => t.Length == 0 ? "~E" : t.Trim().Length == 0 ? "~S" : t;
string Changes(IReadOnlyList<NavMeshTileChange> c) =>
    c.Count == 0 ? "-" : string.Join(';', c.Select(x => $"{x.TileX},{x.TileZ},{x.NewTexture ?? "~N"},{(x.NewCollision.HasValue ? x.NewCollision.Value.ToString() : "~N")}"));
string Action(NavMeshRepairAction a) =>
    $"{a.Id} {a.Kind} {Coord(a.FocusLocation)} {Changes(a.Changes)} | {a.TitleZh} | {a.TitleEn} | {a.DescriptionZh} | {a.DescriptionEn}";

var sb = new StringBuilder();
sb.AppendLine("# generated by tools/csharp-golden-roads from src.MapEditor.Modules/Pathfinding; do not edit");
float[] worlds = [16384f, 16384f, 1000f, 7777.5f];
string[] pool = ["gras", "sand", "H_WEG1", "V_WEG1", "WEG_H1ROM", "WEG_V2", "weg2", "PFAD1", "Pflaster_braun1", "ROMAN", "xWEG_1", "h_weg3", "Weg", "stein", "", "  "];
int id = 0;

byte[]? RandCollision(int size, int density)
{
    int m = Rnd(12);
    if (m == 0) return null;
    if (m == 1) return new byte[size * size + 1];
    var c = new byte[size * size];
    for (int k = 0; k < c.Length; k++) c[k] = Rnd(100) < density ? (byte)(Rnd(255) + 1) : (byte)0;
    return c;
}

void Emit(int size, byte[]? collision, int hs, byte[]? heights, float step, float water, float world,
    int dim, string[] textures, List<(int, int)> seeds, List<(int, int)> interest, int minIso, int maxGap)
{
    var grid = new NavMeshPassabilityGrid(size, collision, hs, heights, step, water, world);
    sb.AppendLine($"CASE {id++}");
    sb.AppendLine($"GRID {size} {F(world)} {Hex(collision)} {hs} {F(step)} {F(water)} {Hex(heights)}");
    sb.AppendLine($"SEEDS {Pts(seeds)}");
    sb.AppendLine($"INTEREST {Pts(interest)}");
    sb.AppendLine($"MIN {minIso}");
    var regions = NavMeshConnectivityAnalyzer.Analyze(grid,
        seeds.Select(s => new NavMeshCoordinate(s.Item1, s.Item2, 0, 0)).ToArray(),
        interest.Select(s => new NavMeshCoordinate(s.Item1, s.Item2, 0, 0)).ToArray(), minIso);
    foreach (var r in regions)
    {
        var b = r.RecommendedBridgePoint;
        sb.AppendLine($"ISO {r.ComponentId} {r.TileCount} {Coord(r.Centroid)} {r.MinTileX} {r.MinTileZ} {r.MaxTileX} {r.MaxTileZ} {(r.ContainsTroopOrBuilding ? 1 : 0)} {r.BridgeDistance} {(b.HasValue ? Coord(b.Value) : "-")}");
        foreach (int bdim in new[] { 0, 64, dim })
        {
            var a = RoadPathHealer.CreateBridgeAction(r, "H_WEG1", bdim);
            sb.AppendLine($"BRIDGE {bdim} {(a is null ? "none" : Action(a))}");
        }
    }
    sb.AppendLine($"ROADS {dim} {maxGap} {string.Join(' ', textures.Select(Tex))}");
    foreach (bool withGrid in new[] { false, true })
    {
        var g = RoadGapDetector.DetectGaps(dim, textures, withGrid ? grid : null, maxGap);
        sb.AppendLine($"GAPS {(withGrid ? 1 : 0)} {g.Count}");
        foreach (var c in g)
            sb.AppendLine($"GAP {Coord(c.Start)} {Coord(c.End)} {Pts(c.GapTiles.Select(t => (t.TileX, t.TileZ)))} {c.GapDistance} {c.SuggestedTexture} {(c.RequiresCollisionClear ? 1 : 0)} {c.Style}");
        foreach (var a in RoadPathHealer.CreateRepairActions(g)) sb.AppendLine("HEAL " + Action(a));
    }
    sb.AppendLine("END");
}

List<(int, int)> RandPts(int size, int max)
{
    var l = new List<(int, int)>();
    int n = Rnd(max + 1);
    for (int i = 0; i < n; i++) l.Add((Rnd(size + 2) - 1, Rnd(size + 2) - 1));
    return l;
}

int[] densities = [0, 10, 25, 40, 55];
for (int i = 0; i < 160; i++)
{
    int size = i < 30 ? 1 + i : 1 + Rnd(28);
    var collision = RandCollision(size, densities[Rnd(densities.Length)]);
    int hs = 0; byte[]? heights = null; float step = 4f, water = 0f;
    int hmode = Rnd(4);
    if (hmode != 0)
    {
        hs = hmode == 1 ? size + 1 : hmode == 2 ? Math.Max(1, size / 2 + 1) : size * 2 + 1;
        heights = new byte[hs * hs];
        for (int k = 0; k < heights.Length; k++) heights[k] = (byte)Rnd(256);
        step = Rnd(2) == 0 ? 4f : 1.5f;
        water = Rnd(300);
    }
    int[] dims = [size, size, Math.Max(1, size / 2), size * 2, 3, 1];
    int dim = dims[Rnd(dims.Length)];
    var tex = new string[dim * dim];
    int roadChance = new[] { 10, 25, 50 }[Rnd(3)];
    for (int k = 0; k < tex.Length; k++) tex[k] = Rnd(100) < roadChance ? pool[2 + Rnd(pool.Length - 2)] : pool[Rnd(2)];
    Emit(size, collision, hs, heights, step, water, worlds[Rnd(worlds.Length)], dim, tex,
        RandPts(size, 3), RandPts(size, 6), new[] { 0, 1, 1, 2, 4 }[Rnd(5)], new[] { 0, 1, 2, 2, 3, 4 }[Rnd(6)]);
}
// Structured road lines with 1-4 tile breaks, mixed styles and a collision plug in even gaps.
foreach (var style in new[] { "H_WEG1", "WEG_H1ROM", "PFAD1", "weg2" })
foreach (int gapLen in new[] { 1, 2, 3, 4 })
{
    int size = 16;
    var tex = Enumerable.Repeat("gras", size * size).ToArray();
    for (int x = 1; x < 15; x++) if (x < 5 || x >= 5 + gapLen) tex[4 * size + x] = style;
    for (int z = 7; z < 15; z++) if (z < 9 || z >= 9 + gapLen) tex[z * size + 3] = style == "H_WEG1" ? "V_WEG1" : style;
    tex[10 * size + 10] = style; tex[12 * size + 12] = style;
    var coll = new byte[size * size];
    if (gapLen % 2 == 0) coll[4 * size + 5] = 9;
    Emit(size, coll, 0, null, 4f, 0f, 16384f, size, tex, new() { (0, 0) }, new(), 1, 2);
}
// Isolated land behind walls of thickness 1..14 (bridge depth limit is 12).
foreach (int thick in new[] { 1, 2, 3, 4, 5, 8, 12, 13, 14 })
{
    int size = 40;
    var coll = new byte[size * size];
    for (int z = 0; z < size; z++) for (int x = 10; x < 10 + thick; x++) coll[z * size + x] = 255;
    Emit(size, coll, 0, null, 4f, 0f, 16384f, size, Enumerable.Repeat("gras", size * size).ToArray(),
        new() { (2, 2) }, new() { (35, 20) }, 1, 2);
    Emit(size, coll, 0, null, 4f, 0f, 16384f, 20, Enumerable.Repeat("gras", 400).ToArray(),
        new(), new() { (35, 20) }, 1, 2);
}
File.WriteAllText(args[0], sb.ToString());
Console.WriteLine($"wrote {id} cases to {args[0]}");
